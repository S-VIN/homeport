-- The kernel's own tables. IF NOT EXISTS: databases made before the scripts.
CREATE TABLE IF NOT EXISTS kernel_migrations (id TEXT NOT NULL PRIMARY KEY, at INT NOT NULL) STRICT;
CREATE TABLE IF NOT EXISTS kernel_plugins (id TEXT NOT NULL PRIMARY KEY, enabled INT NOT NULL) STRICT;
CREATE TABLE IF NOT EXISTS kernel_settings (id TEXT NOT NULL PRIMARY KEY, json TEXT NOT NULL) STRICT;
CREATE TABLE IF NOT EXISTS kernel_order (id TEXT NOT NULL PRIMARY KEY, list TEXT NOT NULL, position INT NOT NULL) STRICT;
